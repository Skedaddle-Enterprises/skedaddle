#!/usr/bin/env node
// Builds tokens.css (CSS custom properties) from tokens.json.
// Run with: node packages/tokens/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(__dirname, 'tokens.json'), 'utf8'));

function typeScale(base, ratio, steps = 6) {
  const lines = [];
  for (let i = -1; i <= steps; i++) {
    const px = base * Math.pow(ratio, i);
    const name = i === -1 ? '--font-size--1' : `--font-size-${i}`;
    lines.push(`  ${name}: ${px.toFixed(3)}px;`);
  }
  return lines.join('\n');
}

const css = `/* AUTO-GENERATED by packages/tokens/build.mjs — do not edit by hand. */
:root {
${Object.entries(tokens.color)
  .map(([k, v]) => `  --color-${k}: ${v};`)
  .join('\n')}

  --font-display: '${tokens.font.display}', serif;
  --font-body: '${tokens.font.body}', sans-serif;

  --scale-base: ${tokens.scale.base}px;
  --scale-ratio: ${tokens.scale.ratio};
${typeScale(tokens.scale.base, tokens.scale.ratio)}
}
`;

writeFileSync(join(__dirname, 'tokens.css'), css);
console.log('Wrote packages/tokens/tokens.css');
